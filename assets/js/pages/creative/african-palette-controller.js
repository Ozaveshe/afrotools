var PALETTE_ENGINE=window.AfroTools&&window.AfroTools.AfricanPaletteEngine;
if(!PALETTE_ENGINE)throw new Error('AfricanPaletteEngine is unavailable');
var PALETTES=PALETTE_ENGINE.palettes;
var hexToRgb=PALETTE_ENGINE.hexToRgb;
var contrastRatio=PALETTE_ENGINE.contrastRatio;
var isDark=PALETTE_ENGINE.isDark;
var current='kente';

function renderStyleGrid(){
  var el=document.getElementById('style-grid');
  el.innerHTML=Object.keys(PALETTES).map(function(key){
    var p=PALETTES[key];
    var swatches=p.colors.map(function(c){return '<span style="background:'+c.hex+'"></span>';}).join('');
    return '<div class="style-chip'+(key===current?' active':'')+'" onclick="selectPalette(\''+key+'\')">'+
      '<div class="style-chip-swatch">'+swatches+'</div>'+
      p.emoji+' '+p.name+
    '</div>';
  }).join('');
}

function selectPalette(key){
  current=key;
  renderStyleGrid();
  renderPalette();
}

function renderPalette(){
  var p=PALETTES[current];
  document.getElementById('palette-title').textContent=p.name;

  // Big display
  var disp=document.getElementById('palette-display');
  disp.innerHTML=p.colors.map(function(c){
    return '<div class="palette-swatch" style="background:'+c.hex+'" title="'+c.name+'">'+
      '<button type="button" class="palette-swatch-copy" onclick="copyHex(\''+c.hex+'\',event)">Copy</button>'+
      '<span class="palette-swatch-hex">'+c.hex+'</span>'+
    '</div>';
  }).join('');

  // Color list
  var list=document.getElementById('color-list');
  list.innerHTML=p.colors.map(function(c){
    var rgb=hexToRgb(c.hex);
    var textColor=isDark(c.hex)?'#fff':'#111';
    return '<div class="color-item">'+
      '<div class="color-item-swatch" style="background:'+c.hex+'" onclick="copyHex(\''+c.hex+'\',event)" title="Click to copy">'+
        '<div style="position:absolute;inset:0;display:flex;align-items:center;justify-content:center;color:'+textColor+';font-size:.68rem;opacity:0;transition:opacity .15s;font-weight:700" class="hover-copy-hint">📋 Copy</div>'+
      '</div>'+
      '<div class="color-item-body">'+
        '<div class="color-item-name">'+c.name+'</div>'+
        '<div class="color-item-hex" onclick="copyHex(\''+c.hex+'\',event)" style="cursor:pointer" title="Click to copy">'+c.hex+'</div>'+
        '<div class="color-item-rgb">rgb('+rgb.r+', '+rgb.g+', '+rgb.b+')</div>'+
      '</div>'+
    '</div>';
  }).join('');

  // CSS output
  var cssLines=['/* African Color Palette: '+p.name+' */','/* Generated by AfroTools — afrotools.com */','',':root {'];
  p.colors.forEach(function(c){cssLines.push('  --color-'+c.role+': '+c.hex+';');});
  cssLines.push('}');
  p.colors.forEach(function(c){
    cssLines.push('');
    cssLines.push('/* '+c.name+' */');
    cssLines.push('.bg-'+c.role+' { background-color: var(--color-'+c.role+'); }');
    cssLines.push('.text-'+c.role+' { color: var(--color-'+c.role+'); }');
    cssLines.push('.border-'+c.role+' { border-color: var(--color-'+c.role+'); }');
  });
  document.getElementById('css-code').textContent=cssLines.join('\n');

  // Tailwind
  var twObj={};
  p.colors.forEach(function(c){twObj[c.role]=c.hex;});
  var twLines=[
    '// tailwind.config.js — '+p.name+' palette',
    '// Generated by AfroTools',
    '',
    'module.exports = {',
    '  theme: {',
    '    extend: {',
    '      colors: {',
    '        african: {',
  ];
  p.colors.forEach(function(c){twLines.push("          '"+c.role+"': '"+c.hex+"',");});
  twLines.push('        },');
  twLines.push('      },');
  twLines.push('    },');
  twLines.push('  },');
  twLines.push('};');
  document.getElementById('tw-code').textContent=twLines.join('\n');
  if(window.AfroToolsCreativeResultActions){
    window.AfroToolsCreativeResultActions.publish({
      slug:'african-palette-'+current,
      title:'African palette: '+p.name,
      result:{palette:p.name,colors:p.colors,css:cssLines.join('\n'),tailwind:twLines.join('\n')},
      target:document.getElementById('tool-mount')||document.querySelector('.en-tool-layout')
    });
  }

  // Contrast
  var bgColor=p.colors.find(function(c){return c.role==='background';});
  var bg=bgColor?bgColor.hex:'#ffffff';
  var contrastEl=document.getElementById('contrast-list');
  contrastEl.innerHTML='<p style="font-size:.82rem;color:var(--en-muted);margin-bottom:12px">Contrast ratio against background ('+bg+')</p>'+
    p.colors.filter(function(c){return c.role!=='background';}).map(function(c){
    var ratio=contrastRatio(c.hex,bg);
    var aa=ratio>=4.5;
    var aaLg=ratio>=3;
    return '<div class="contrast-row">'+
      '<div style="width:24px;height:24px;border-radius:6px;background:'+c.hex+';border:1px solid rgba(0,0,0,.1);flex-shrink:0"></div>'+
      '<span style="flex:1;font-size:.84rem;font-weight:600">'+c.name+' ('+c.hex+')</span>'+
      '<span class="contrast-score">'+ratio.toFixed(2)+':1</span>'+
      '<span class="contrast-badge '+(aa?'aa-pass':'aa-fail')+'">'+(aa?'AA Pass':'AA Fail')+'</span>'+
      '<span class="contrast-badge '+(aaLg?'aa-pass':'aa-fail')+'">'+(aaLg?'AA Lg Pass':'AA Lg Fail')+'</span>'+
    '</div>';
  }).join('');
}

function copyHex(hex,e){
  if(e)e.stopPropagation();
  navigator.clipboard.writeText(hex).then(function(){
    var el=e&&e.target;
    if(el){var old=el.textContent;el.textContent='✅';setTimeout(function(){el.textContent=old;},1200);}
  });
}

function copyTabCode(id){
  var txt=document.getElementById(id).textContent;
  navigator.clipboard.writeText(txt).then(function(){
    var btn=event.target;btn.textContent='✅ Copied!';btn.classList.add('copied');
    setTimeout(function(){btn.textContent='📋 Copy '+(id.includes('css')?'CSS':'Config');btn.classList.remove('copied');},2000);
  });
}

function showTab(id,btn){
  document.querySelectorAll('.tab-pane').forEach(function(p){p.classList.remove('active');});
  document.querySelectorAll('.tab-btn').forEach(function(b){b.classList.remove('active');});
  document.getElementById('tab-'+id).classList.add('active');
  btn.classList.add('active');
}

renderStyleGrid();
renderPalette();
