const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const source = fs.readFileSync(path.join(__dirname, "..", "engines", "src", "creator-calendar-engine.js"), "utf8");
const context = {console, Date, Math, JSON, Number, String, Array, Object, URLSearchParams, crypto: {randomUUID: () => "fixture-id"}, localStorage: {getItem: () => null, setItem: () => {}}};
vm.runInNewContext(source, context);
const engine = context.CreatorCalendarEngine;
const plan = engine.buildLocalPlan({topic: "Mode durable", startDate: "2026-08-01", days: 7, country: "SN", platforms: ["instagram", "linkedin"]});
assert.equal(plan.posts.length, 7);
assert.equal(plan.posts[0].date, "2026-08-01");
assert.equal(plan.posts[6].date, "2026-08-07");
assert.deepEqual(Array.from(new Set(plan.posts.map(post => post.platform))), ["instagram", "linkedin"]);
assert.equal(plan.posts[0].angle, "educate");
assert.throws(() => engine.buildLocalPlan({topic: "", startDate: "2026-08-01", days: 7, platforms: ["instagram"]}), /topic/);
assert.throws(() => engine.buildLocalPlan({topic: "x", startDate: "2026-08-01", days: 32, platforms: ["instagram"]}), /between 1 and 31/);
assert.throws(() => engine.buildLocalPlan({topic: "x", startDate: "bad", days: 7, platforms: ["instagram"]}), /valid start date/);
assert.throws(() => engine.buildLocalPlan({topic: "x", startDate: "2026-08-01", days: 7, platforms: []}), /platform/);
console.log("creator-calendar native engine: 8 assertions passed");
