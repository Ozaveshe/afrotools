const { test, expect } = require('@playwright/test');
test('ZA household LPG lookup, two schedules and net-mass calculation remain honest on mobile',async({page})=>{
  await page.setViewportSize({width:390,height:844});
  await page.goto('/tools/fuel-tracker/south-africa/');
  const host=page.locator('[data-za-lpg-calculator]'),result=host.locator('[data-za-lpg-result]');
  await host.locator('#zaLpgDistrict').fill('Johannesburg');
  await host.locator('#zaLpgDistrict').press('Enter');
  await host.getByRole('button',{name:/Johannesburg.*zone 9C/}).click();
  await expect(host.locator('#zaLpgZone')).toHaveValue('9C');
  await host.locator('#zaLpgSupply').selectOption('general');
  await host.locator('#zaLpgKg').fill('9');
  await host.getByRole('button',{name:'Calculate dated refill reference'}).click();
  await expect(result).toContainText('R356.76');
  await host.locator('#zaLpgKg').fill('19');
  await expect(result).toBeHidden();
  await host.locator('#zaLpgZone').selectOption('1A');
  await host.locator('#zaLpgSupply').selectOption('unknown');
  await host.locator('#zaLpgKg').fill('9');
  await host.getByRole('button',{name:'Calculate dated refill reference'}).click();
  await expect(result).toContainText('R327.51');await expect(result).toContainText('R352.44');
  await expect(result).toContainText('Supply route unconfirmed');
  await host.locator('#zaLpgSupply').selectOption('saldanha');
  await host.locator('#zaLpgKg').fill('19');
  await host.getByRole('button',{name:'Calculate dated refill reference'}).click();
  await expect(result).toContainText('R744.04');
  await host.locator('#zaLpgKg').fill('-1');
  await host.getByRole('button',{name:'Calculate dated refill reference'}).click();
  await expect(result).toBeHidden();await expect(host.locator('[data-za-lpg-status]')).toContainText('more than 0');
  await expect(host.locator('[data-za-lpg-status]')).toBeInViewport();
  await host.locator('#zaLpgKg').fill('');await host.locator('#zaLpgKg').pressSequentially('e');
  expect(await host.locator('#zaLpgKg').evaluate(input=>input.validity.badInput)).toBe(true);
  await host.getByRole('button',{name:'Calculate dated refill reference'}).click();
  await expect(result).toBeHidden();await expect(host.locator('[data-za-lpg-status]')).toContainText('valid LPG mass');
  await host.locator('#zaLpgKg').fill('9');
  await host.locator('#zaLpgZone').selectOption('9C');
  await host.getByRole('button',{name:'Calculate dated refill reference'}).click();
  await expect(host.locator('[data-za-lpg-status]')).toContainText('does not list');
  await host.locator('#zaLpgSupply').selectOption('unknown');
  await host.getByRole('button',{name:'Calculate dated refill reference'}).click();
  await expect(result).toContainText('R356.76');await expect(result).toContainText('absence is not proof');
  await host.getByRole('button',{name:'Reset LPG calculator'}).click();await expect(result).toBeHidden();
  await host.locator('#zaLpgDistrict').fill('Malmesbury');await host.locator('#zaLpgFind').click();
  await expect(host.locator('[data-za-lpg-matches] button')).toHaveCount(2);
  await expect(host.locator('[data-za-lpg-matches]')).toContainText('boundary confirmation');
  expect(await host.locator('form').evaluate(form=>[...new FormData(form).entries()])).toEqual([]);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
