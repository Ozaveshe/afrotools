const { test, expect } = require('@playwright/test');
test.use({ reducedMotion: 'reduce', viewport: { width: 375, height: 812 } });
test('renovation estimate and itemized budget entry', async ({ page }) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.stack || error.message));
  await page.goto('/tools/home-renovation-cost/');
  await expect(page.getByRole('heading', { name: 'Home Renovation Cost Calculator', exact: true })).toBeVisible();
  await expect(page.locator('[data-result]')).toBeEmpty();
  await page.getByLabel('Currency (for example, NGN or ZAR)', { exact: true }).fill('TEST');
  await page.getByLabel('Measured quantity or area', { exact: true }).fill('40');
  await page.getByLabel('Quoted cost per unit or square metre', { exact: true }).fill('50');
  await page.getByLabel('Additional fixed costs', { exact: true }).fill('200');
  await page.getByLabel('Contingency allowance (%)', { exact: true }).fill('10');
  await page.getByRole('button', { name: 'Calculate from my inputs', exact: true }).click();
  await expect(page.locator('[data-result]')).toContainText('TEST 2,420');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBeTruthy();
  await page.getByRole('button', { name: 'Reset', exact: true }).click();
  await expect(page.locator('[data-result]')).toBeEmpty();
  await expect(page.getByLabel('Measured quantity or area', { exact: true })).toHaveValue('');
  expect(errors).toEqual([]);
  await page.getByRole('link', { name: 'Build an itemized renovation BOQ', exact: true }).click();
  await expect(page).toHaveURL(/\/tools\/boq-builder\/app(?:\.html)?$/);
  await page.getByRole('button', { name: 'Templates', exact: true }).click();
  await expect(page.getByText('Residential Renovation', { exact: true })).toBeVisible();
  page.once('dialog', dialog => dialog.accept());
  await page.getByText('Residential Renovation', { exact: true }).click();
  await expect(page.locator('input[value="Protection of existing finishes"]')).toBeVisible();
  expect(errors).toEqual([]);
});
