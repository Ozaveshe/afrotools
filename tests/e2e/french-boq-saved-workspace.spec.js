const { test, expect } = require('@playwright/test');
const fs = require('node:fs');
test('French BOQ saved draft opens the same record in the disclosed English workspace by keyboard', async ({ page }, info) => {
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.setViewportSize({width:390,height:844});
  await page.goto('/fr/tools/devis-quantitatif/',{waitUntil:'domcontentloaded'});
  await expect(page.locator('#saved-section')).toBeHidden();
  const create=page.locator('a.landing-cta-primary[href="/tools/boq-builder/app"]').first();
  await create.focus();await expect(create).toBeFocused();
  await Promise.all([page.waitForURL(url=>url.pathname==='/tools/boq-builder/app'),page.keyboard.press('Enter')]);
  await page.locator('#projName').fill('Synthetic saved BOQ journey');
  await page.locator('#projClient').fill('Synthetic local client');
  const saved=page.waitForEvent('dialog').then(async dialog=>{
    const observed={type:dialog.type(),message:dialog.message()};await dialog.accept();
    expect(observed).toEqual({type:'alert',message:'BOQ saved!'});return observed;
  });
  const [alert]=await Promise.all([saved,page.locator('button[onclick="saveBOQ()"]').click()]);
  await page.goBack({waitUntil:'domcontentloaded'});
  await expect(page).toHaveURL(/\/fr\/tools\/devis-quantitatif\/$/);
  const section=page.locator('#saved-section');await expect(section).toBeVisible();
  const card=page.locator('#saved-boqs .saved-card');await expect(card).toHaveCount(1);
  await expect(card.locator('.saved-card-title')).toHaveText('Synthetic saved BOQ journey');
  const id=await card.getAttribute('data-id');expect(id).toBeTruthy();
  const open=card.locator('a.saved-card-open');await expect(open).toBeVisible();
  await expect(open).toHaveAttribute('href','/tools/boq-builder/app?id='+encodeURIComponent(id));
  await expect(open).toHaveText('Ouvrir ce devis (éditeur en anglais)');
  await expect(open).toHaveAttribute('hreflang','en');
  await expect(open).toHaveAttribute('aria-label','Ouvrir ce devis dans l’éditeur de devis (en anglais)');
  await open.scrollIntoViewIfNeeded();
  const bounds=await open.boundingBox();expect(bounds.x).toBeGreaterThanOrEqual(0);expect(bounds.x+bounds.width).toBeLessThanOrEqual(391);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
  await section.screenshot({path:info.outputPath('saved-boq-disclosed-workspace-390.png'),scale:'css'});
  await open.focus();await expect(open).toBeFocused();
  await Promise.all([page.waitForURL(url=>url.pathname==='/tools/boq-builder/app'&&url.searchParams.get('id')===id),page.keyboard.press('Enter')]);
  await expect(page.locator('html')).toHaveAttribute('lang','en');await expect(page).toHaveTitle('BOQ Builder | AfroTools');
  await expect(page.locator('#projName')).toHaveValue('Synthetic saved BOQ journey');
  await expect(page.locator('#projClient')).toHaveValue('Synthetic local client');
  expect(errors).toEqual([]);
  fs.writeFileSync(info.outputPath('saved-boq-roundtrip-observations.json'),JSON.stringify({id,url:page.url(),alert,keyboard:'Enter',sameRecordLoaded:true,project:'Synthetic saved BOQ journey',client:'Synthetic local client',linkBounds:bounds,pageErrors:errors,qualification:'Synthetic device-local Save/restore; no account sync, provider or production proof.'},null,2)+'\n',{flag:'wx'});
});
