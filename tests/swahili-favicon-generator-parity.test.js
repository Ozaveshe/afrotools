#!/usr/bin/env node
'use strict';
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');
const ROOT = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(ROOT, file), 'utf8');
const english = read('tools/favicon-generator/index.html');
const swahili = read('sw/zana/kizalishaji-favicon/index.html');
const engine = read('assets/js/lib/favicon-generator-studio.js');
const registry = read('assets/js/components/tool-registry.js');
const manifest = JSON.parse(read('data/localization/sw-image-design-parity.json'));
const built = spawnSync(process.execPath, ['scripts/build-sw-favicon-generator.js', '--check'], { cwd: ROOT, encoding: 'utf8' });
assert.strictEqual(built.status, 0, built.stderr || built.stdout);
assert.match(swahili, /<html\b[^>]*lang="sw"/);
assert.ok(swahili.includes('Source owner: scripts/build-sw-favicon-generator.js; engine: assets/js/lib/favicon-generator-studio.js'));
assert.ok(english.includes('/assets/js/lib/favicon-generator-studio.js'));
assert.ok(swahili.includes('/assets/js/lib/favicon-generator-studio.js'));
assert.ok(!/<iframe\b/i.test(swahili));
assert.ok(!/<script\b[^>]+src="https?:\/\//i.test(swahili));
assert.ok(!/\b(?:fetch|XMLHttpRequest|WebSocket|sendBeacon)\s*\(/.test(engine));
for (const token of ['const sizes = [16, 32, 48, 64]', "zip.file('favicon.ico'", "zip.file('site.webmanifest'", 'window.AfroTools.faviconStudio', "imageInput.addEventListener('change'", "resetBtn.addEventListener('click'"]) assert.ok(engine.includes(token), `shared owner missing ${token}`);
assert.ok(swahili.includes('<link rel="canonical" href="https://afrotools.com/sw/zana/kizalishaji-favicon/">'));
for (const [lang, route] of [['en', '/tools/favicon-generator/'], ['fr', '/fr/tools/generateur-favicon/'], ['sw', '/sw/zana/kizalishaji-favicon/']]) assert.ok(swahili.includes(`hreflang="${lang}" href="https://afrotools.com${route}"`));
assert.ok(english.includes('hreflang="sw" href="https://afrotools.com/sw/zana/kizalishaji-favicon/"'));
assert.ok(read('fr/tools/generateur-favicon/index.html').includes('hreflang="sw" href="https://afrotools.com/sw/zana/kizalishaji-favicon/"'));
assert.ok(swahili.includes('https://afrotools.com/assets/img/tools/favicon-generator.webp'));
assert.ok(fs.existsSync(path.join(ROOT, 'assets/img/tools/favicon-generator.webp')));
for (const match of swahili.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)) JSON.parse(match[1]);
assert.ok(swahili.includes('"inLanguage":"sw"'));
assert.ok(registry.includes('id: "zana-kizalishaji-favicon-sw"'));
assert.ok(registry.includes('href: "/sw/zana/kizalishaji-favicon/"'));
assert.strictEqual(manifest.rows.find(row => row.id === 'favicon-generator').status, 'accepted-candidate');
console.log('Swahili favicon static parity: shared local owner, PNG/ICO/manifest ZIP, reset, SEO, artwork and discovery passed.');
