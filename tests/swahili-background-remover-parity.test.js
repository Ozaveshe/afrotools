'use strict';

const assert = require('assert');
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const manifest = JSON.parse(read('data/localization/sw-image-design-parity.json'));
const row = manifest.rows.find(item => item.id === 'background-remover');
const sw = read('sw/zana/kiondoa-mandharinyuma/index.html');
const en = read('tools/background-remover/index.html');
const fr = read('fr/tools/supprimer-arriere-plan/index.html');

assert(row, 'background-remover manifest row missing');
assert.strictEqual(row.status, 'accepted-candidate');
assert(row.sourceOwner.includes('build-sw-background-remover.js'));
assert(row.sourceOwner.includes('background-remover-studio.js'));
assert(sw.includes('Generated by scripts/build-sw-background-remover.js'));
assert(sw.includes('/assets/js/lib/background-remover-studio-sw.js'));
assert(sw.includes('/assets/js/lib/background-remover-studio.js'));
assert(!/<iframe\b/i.test(sw), 'Swahili owner must not use an iframe');
assert(!/Open English|Continue in English|English studio/i.test(sw), 'English handoff leaked into native owner');
assert(sw.includes('https://afrotools.com/sw/zana/kiondoa-mandharinyuma/'));
assert(sw.includes('https://afrotools.com/assets/img/tools/background-remover.webp'));
assert(en.includes('hreflang="sw"') && en.includes('/sw/zana/kiondoa-mandharinyuma/'));
assert(fr.includes('hreflang="sw"') && fr.includes('/sw/zana/kiondoa-mandharinyuma/'));
assert(!/\b(?:fetch|XMLHttpRequest|WebSocket|sendBeacon)\s*\(/.test(sw), 'Swahili page contains a direct network-write primitive');

const requiredSwahili = [
  'Ondoa mandharinyuma',
  'Picha chanzo',
  'Mpangilio wa kukata picha',
  'Safisha kingo',
  'Andaa faili',
  'Picha chanzo hubaki kwenye kifaa hiki'
];
requiredSwahili.forEach(value => assert(sw.includes(value), `missing Swahili contract copy: ${value}`));

console.log('Swahili Background Remover static parity: 1/1 route contract passed.');
