const target=path.join(root,'assets/js/lib/leave-holiday-reference.js');
if(process.argv.includes('--check')){if(fs.readFileSync(target,'utf8')!==output)throw new Error('Leave holiday reference is stale');}else fs.writeFileSync(target,output);
