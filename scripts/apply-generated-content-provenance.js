#!/usr/bin/env node
'use strict';

const fs = require('fs');
const path = require('path');
const { ROOT, routeForFile, stableId } = require('./lib/content-integrity');
const { writeFileSyncWithRetry } = require('./lib/safe-write');

const WRITE = process.argv.includes('--write');
const CHECK = process.argv.includes('--check') || !WRITE;
const SKIP_DIRS = new Set([
  '.agents', '.claude', '.git', '.jamb-tools', '.playwright', '.cache',
  'afrotools-deploy', 'artifacts', 'audit-results', 'dist', 'node_modules', 'output',
  'playwright-report', 'reports', 'test-results', 'tests'
]);

function walk(directory, output = []) {
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    if (entry.isDirectory() && SKIP_DIRS.has(entry.name)) continue;
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) walk(absolute, output);
    else if (entry.isFile() && entry.name.endsWith('.html')) output.push(absolute);
  }
  return output;
}

function hasMeta(html, name) {
  return new RegExp(`<meta\\b(?=[^>]*\\bname=["']${name}["'])[^>]*>`, 'i').test(html);
}

function isGenerated(html) {
  return /<!--\s*Generated by\s+/i.test(html)
    || /name=["']afrotools(?:-[a-z]{2})?-source-hash["']/i.test(html)
    || hasMeta(html, 'afrotools-source-owner');
}

function insertContentId(html, id) {
  if (!/<\/head>/i.test(html)) throw new Error('Generated HTML has no closing head element.');
  return html.replace(/<\/head>/i, `<meta name="afrotools-content-id" content="${id}">\n</head>`);
}

function main() {
  const stale = [];
  let updated = 0;
  for (const absolute of walk(ROOT)) {
    const relative = path.relative(ROOT, absolute).replace(/\\/g, '/');
    if (relative.startsWith('data/localization/')) continue;
    const before = fs.readFileSync(absolute, 'utf8');
    if (!isGenerated(before) || hasMeta(before, 'afrotools-content-id')) continue;
    const route = routeForFile(relative);
    if (!route) continue;
    const after = insertContentId(before, stableId(route));
    if (WRITE) writeFileSyncWithRetry(absolute, after, 'utf8');
    else stale.push(relative);
    updated += 1;
  }

  if (CHECK && stale.length) {
    console.error(`Generated content provenance is stale in ${stale.length} page(s):\n${stale.slice(0, 80).join('\n')}`);
    process.exitCode = 1;
    return;
  }
  console.log(`${WRITE ? 'Applied' : 'Checked'} generated content provenance: ${updated} page(s).`);
}

if (require.main === module) main();

module.exports = { hasMeta, isGenerated, insertContentId };
