"use strict";
// Package the web HR engine and its overtime data for the server without executing source at runtime.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const owners = ['data/hr/overtime-rules.js', 'data/hr/minimum-wages.js', 'data/hr/leave-entitlements.js', 'engines/src/hr-engine.js'];
const output = path.join(root, 'netlify/functions/_shared/whatsapp-hr-runtime.js');
const bundle = "// Generated by scripts/build-whatsapp-hr-runtime.js. Edit the maintained owners.\n'use strict';\nvar window = { AfroTools: {} };\n" + owners.map(file => fs.readFileSync(path.join(root, file), 'utf8')).join('\n') + "\nmodule.exports = { calculateOvertime: window.AfroTools.HREngine.calculateOvertime, overtimeRules: OVERTIME_RULES, minimumWages: MINIMUM_WAGES, leaveEntitlements: LEAVE_ENTITLEMENTS };\n";
if (process.argv.includes('--check')) {
  if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== bundle) throw new Error('Generated WhatsApp HR runtime is stale');
} else {
  fs.writeFileSync(output, bundle);
}
console.log('WhatsApp HR runtime: ' + (process.argv.includes('--check') ? 'verified' : 'generated'));
