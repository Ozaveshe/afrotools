#!/usr/bin/env node
/*
 * Bundles the Afro lexicon and synonym groups into a browser-loadable global.
 *
 * afro-confidence.js takes both as plain options, which is fine in Node where
 * the benchmark can require() the JSON. The browser cannot, and routing is a
 * synchronous path — introducing a fetch there would mean the first query on a
 * cold page routes without them and silently behaves like the old system.
 * Emitting one small script keeps the data available before the first decision.
 *
 * Generated output; edit the JSON sources, not assets/js/ai/afro-data.js.
 */
const fs = require("fs");
const path = require("path");
// OneDrive-synced checkouts throw EPERM on rename; the repo helper retries.
const { writeFileSyncWithRetry } = require("./lib/safe-write");

const ROOT = path.resolve(__dirname, "..");
const OUT = path.join(ROOT, "assets", "js", "ai", "afro-data.js");
const DIR_OUT = path.join(ROOT, "assets", "js", "ai", "afro-directory.js");

/*
 * The browser had NO tool directory at all.
 *
 * tool-manifest.js reads data/tool-directory.json via require('fs') in Node and
 * falls back to window.AFROTOOLS_TOOL_DIRECTORY in a browser — which nothing
 * ever set. So loadDefaultToolManifest() returned [], the /ai/ page's
 * getRouterManifest() returned [], and localCatalogRoute() hit its
 * `if (!manifest.length) return null` guard on every single query. The
 * full-catalog fallback has been dead in production, which is why calibrating
 * the router alone changed nothing on the page.
 *
 * SHIP THE DIRECTORY SCHEMA, NOT THE ROUTER SCHEMA. The first version of this
 * emitted getToolManifestForRouter() output, which looks like the right thing
 * and is not: AFROTOOLS_TOOL_DIRECTORY is fed to buildToolManifest(), which
 * expects directory entries ({name, description, category_key, url…}) and
 * DERIVES the router fields (userIntents, exampleQueries, slug…) from them.
 * Feeding it router entries produced a manifest with the vocabulary stripped
 * out — every query collapsed to "tied_candidates", so "calculate PAYE take
 * home pay … in Kenya" scored 0.2. It routed to the right tool and reported it
 * as a coin flip. Directory shape is also smaller (81 KB gz vs 139 KB) because
 * the derived fields are rebuilt at load instead of shipped.
 */
function writeDirectory() {
  const directory = JSON.parse(fs.readFileSync(path.join(ROOT, "data", "tool-directory.json"), "utf8"));

  /* Afro 1.3 — fold the vocabulary pack in as aliases.
   *
   * Aliases are already scored by rankToolCandidates, so this needs no change
   * to the ranker: a tool simply now contains the words users type. Delivered
   * here rather than written back into tool-directory.json so the generated
   * vocabulary never contaminates the hand-maintained source, and regenerating
   * it can never silently rewrite the catalog. */
  const vocabPath = path.join(ROOT, "data", "ai", "afro-vocabulary.json");
  let enriched = 0;
  if (fs.existsSync(vocabPath)) {
    const pack = JSON.parse(fs.readFileSync(vocabPath, "utf8")).tools || {};
    directory.forEach((tool) => {
      const extra = pack[tool.id];
      if (!extra || !extra.length) return;
      const seen = new Set((tool.aliases || []).map((a) => String(a).toLowerCase()));
      const merged = (tool.aliases || []).slice();
      extra.forEach((term) => {
        if (seen.has(String(term).toLowerCase())) return;
        seen.add(String(term).toLowerCase());
        merged.push(term);
      });
      tool.aliases = merged;
      enriched += 1;
    });
  }
  console.log("  vocabulary pack applied to " + enriched + " tools");

  const js = "/* GENERATED by scripts/build-afro-data.js — do not edit. */\n"
    + "(function(root){root.AFROTOOLS_TOOL_DIRECTORY=" + JSON.stringify(directory) + ";})"
    + "(typeof globalThis!==\"undefined\"?globalThis:this);\n";
  writeFileSyncWithRetry(DIR_OUT, js, "utf8");
  console.log("Wrote assets/js/ai/afro-directory.js — " + directory.length + " tools, "
    + Math.round(js.length / 1024) + " KB raw");
}

function read(name) {
  return JSON.parse(fs.readFileSync(path.join(ROOT, "data", "ai", name), "utf8"));
}

function main() {
  const lexicon = read("afro-lexicon.json");
  const synonyms = read("afro-synonyms.json");

  // Only the fields the runtime actually reads — the benchmarks and provenance
  // notes stay in the JSON and out of the bytes users download.
  const payload = {
    version: "afro-1.3",
    lexicon: { entries: (lexicon.entries || []).map((e) => ({ phrases: e.phrases, tools: e.tools })) },
    synonyms: { groups: (synonyms.groups || []).map((g) => ({ terms: g.terms })) }
  };

  const js = "/* GENERATED by scripts/build-afro-data.js — edit data/ai/afro-*.json instead. */\n"
    + "(function(root){root.AFRO_DATA=" + JSON.stringify(payload) + ";})"
    + "(typeof globalThis!==\"undefined\"?globalThis:this);\n";

  writeFileSyncWithRetry(OUT, js, "utf8");

  const phrases = payload.lexicon.entries.reduce((n, e) => n + (e.phrases || []).length, 0);
  const terms = payload.synonyms.groups.reduce((n, g) => n + (g.terms || []).length, 0);
  writeDirectory();

  console.log(
    "Wrote assets/js/ai/afro-data.js — "
    + payload.lexicon.entries.length + " lexicon entries / " + phrases + " phrases, "
    + payload.synonyms.groups.length + " synonym groups / " + terms + " terms, "
    + Math.round(js.length / 1024) + " KB"
  );
}

main();
