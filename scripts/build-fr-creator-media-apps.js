"use strict";

const fs = require("node:fs");
const path = require("node:path");
const {
  localizeVisibleLanguage,
} = require("./lib/french-visible-language");

const root = path.resolve(__dirname, "..");
const owners = [
  ["creator-clip", "decoupe-de-video-pour-createur", "Espace de découpe vidéo CreatorClip"],
  ["creator-record", "enregistrement-pour-createur", "Espace d'enregistrement CreatorRecord"],
  ["creator-voice", "voix-de-marque-du-createur", "Studio audio CreatorVoice"],
];

function ensureRouteRealProofAssets(html) {
  let next = html;
  if (!next.includes("/assets/css/fr-creative-route-real-proof.css")) {
    next = next.replace(
      "</head>",
      '<link rel="stylesheet" href="/assets/css/fr-creative-route-real-proof.css">\n</head>'
    );
  }
  if (!next.includes("/assets/js/pages/creative/fr-creative-route-real-reflow.js")) {
    next = next.replace(
      "</body>",
      '<script src="/assets/js/pages/creative/fr-creative-route-real-reflow.js" defer></script>\n</body>'
    );
  }
  return next;
}

for (const [id, slug, title] of owners) {
  const source = path.join(root, "tools", id, "app.html");
  const destination = path.join(root, "fr/tools", slug, "app.html");
  const englishUrl = `https://afrotools.com/tools/${id}/app`;
  const frenchUrl = `https://afrotools.com/fr/tools/${slug}/app`;
  let html = fs.readFileSync(source, "utf8");
  html = html
    .replace('lang="en"', 'lang="fr"')
    .replace(/<title>[\s\S]*?<\/title>/, `<title>${title} | AfroTools</title>`)
    .replaceAll(englishUrl, frenchUrl)
    .replace(
      /<link rel="canonical"[^>]*>/,
      `<link rel="canonical" href="${frenchUrl}">\n<link rel="alternate" hreflang="en" href="${englishUrl}">\n<link rel="alternate" hreflang="fr" href="${frenchUrl}">\n<link rel="alternate" hreflang="x-default" href="${englishUrl}">`
    )
    .replace(
      /href="style\.css\?/g,
      `href="/tools/${id}/style.css?`
    )
    .replace(
      `<script src="/assets/js/pages/creative/${id}-app-controller.js"></script>`,
      `<script src="/assets/js/pages/creative/fr-creator-media-localizer.js"></script>\n<script src="/assets/js/pages/creative/${id}-app-controller.js"></script>`
    );
  fs.mkdirSync(path.dirname(destination), { recursive: true });
  fs.writeFileSync(
    destination,
    ensureRouteRealProofAssets(localizeVisibleLanguage(html))
  );
  const landing = path.join(root, "fr/tools", slug, "index.html");
  let landingHtml = fs.readFileSync(landing, "utf8");
  landingHtml = landingHtml
    .replace(
      "<!-- Generated by scripts/generate-fr-tool-gap-pages.js. Edit source data there. -->",
      "<!-- Native French Creator workspace launcher. -->"
    )
    .replace(
      /<meta name="afrotools-source-owner" content="[^"]+">/,
      '<meta name="afrotools-source-owner" content="scripts/build-fr-creator-media-apps.js">'
    )
    .replace(
      /<div id="tool-mount" class="source-launch">[\s\S]*?<\/div>/,
      `<div id="tool-mount" class="source-launch" data-fr-creative-native="${id}"><h2>Ouvrir l'espace de travail</h2><p>L'application française complète fonctionne localement dans votre navigateur. Vos médias ne sont envoyés à aucun serveur.</p><a class="primary-action" href="app.html">Lancer l'application</a></div>`
    )
    .replace(
      /<a class="secondary-action" href="\/tools\/[^"]+\/">[^<]+<\/a>/,
      '<a class="secondary-action" href="app.html">Ouvrir l’espace complet</a>'
    );
  fs.writeFileSync(landing, ensureRouteRealProofAssets(landingHtml));
  process.stdout.write(`${id} -> fr/tools/${slug}/app.html\n`);
}
