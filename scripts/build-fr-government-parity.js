function validate(manifest) {
  if (!manifest || manifest.locale !== 'fr' || !Array.isArray(manifest.apps)) {
    throw new Error('Invalid French Government parity manifest');
  }
  if (manifest.apps.length !== 15) {
    throw new Error(`Expected exactly 15 canonical apps, found ${manifest.apps.length}`);
  }
  const ids = new Set();
  const routes = new Set();
  for (const app of manifest.apps) {
    if (!app.id || !app.route || !app.englishRoute || !app.title || !app.mode) {
      throw new Error(`Incomplete app contract: ${JSON.stringify(app)}`);
    }
    if (ids.has(app.id)) throw new Error(`Duplicate app id: ${app.id}`);
    if (routes.has(app.route)) throw new Error(`Duplicate French route: ${app.route}`);
    if (!fs.existsSync(path.join(ROOT, 'tools', app.id, 'index.html'))) {
      throw new Error(`Missing English canonical owner for ${app.id}`);
    }
    if (!fs.existsSync(path.join(ROOT, 'assets', 'img', 'tools', `${app.id}.webp`))) {
      throw new Error(`Missing canonical artwork for ${app.id}`);
    }
    ids.add(app.id);
    routes.add(app.route);
  }
}

function main() {
  const manifest = JSON.parse(fs.readFileSync(MANIFEST_PATH, 'utf8'));
  validate(manifest);
  const hubOnly = process.argv.includes('--hub-only');
  if (!hubOnly) {
    for (const app of manifest.apps) {
      const filePath = routeToFile(app.route);
      ensureDirectory(filePath);
      fs.writeFileSync(filePath, renderApp(app, manifest.apps, manifest.swAlternates), 'utf8');
    }
  }
  const hubPath = routeToFile(manifest.hubRoute);
  ensureDirectory(hubPath);
  fs.writeFileSync(hubPath, renderHub(manifest), 'utf8');
  process.stdout.write(hubOnly
    ? `Built French Government parity hub: ${manifest.hubRoute}\n`
    : `Built French Government parity: ${manifest.apps.length}/15 apps plus ${manifest.hubRoute}\n`);
}

if (require.main === module) main();

module.exports = { renderApp, renderHub, validate, routeToFile };
