const ROOT = path.resolve(__dirname, '..');
const MANIFEST_PATH = path.join(ROOT, 'data', 'government', 'fr-parity-apps.json');
const SITE = 'https://afrotools.com';

function escapeHtml(value) {
  return String(value == null ? '' : value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function safeJson(value) {
  return JSON.stringify(value).replace(/</g, '\\u003c');
}

function routeToFile(route) {
  return path.join(ROOT, route.replace(/^\/+|\/+$/g, ''), 'index.html');
}

function ensureDirectory(filePath) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
}

function schemaFor(app) {
  return {
    '@context': 'https://schema.org',
    '@graph': [
      {
        '@type': 'WebApplication',
        name: app.title,
        description: app.description,
        url: SITE + app.route,
        applicationCategory: 'GovernmentApplication',
        operatingSystem: 'Any',
        inLanguage: 'fr',
        isAccessibleForFree: true,
        image: `${SITE}/assets/img/tools/${app.id}.webp`,
        isBasedOn: SITE + app.englishRoute,
        offers: { '@type': 'Offer', price: '0', priceCurrency: 'USD' },
        provider: { '@type': 'Organization', name: 'AfroTools', url: SITE }
      },
      {
        '@type': 'BreadcrumbList',
        itemListElement: [
          { '@type': 'ListItem', position: 1, name: 'Accueil', item: `${SITE}/fr/` },
          { '@type': 'ListItem', position: 2, name: 'Gouvernement et démarches', item: `${SITE}/fr/gouvernement/` },
          { '@type': 'ListItem', position: 3, name: app.shortTitle, item: SITE + app.route }
        ]
      }
    ]
  };
}

function relatedCards(apps, currentId) {
  return apps
    .filter((app) => app.id !== currentId)
    .slice(0, 6)
    .map((app) => `<a class="fg-card" href="${app.route}"><strong>${escapeHtml(app.shortTitle)}</strong><span>${escapeHtml(app.description)}</span></a>`)
    .join('');
}

