function replaceFrontPageBlock(current, generated) {
  const start = current.indexOf(FRONT_PAGE_START);
  const end = current.indexOf(FRONT_PAGE_END);
  assert(start !== -1 && end !== -1 && start < end, 'Tracker front-page markers are missing or out of order.');
  assert(current.indexOf(FRONT_PAGE_START, start + FRONT_PAGE_START.length) === -1, 'Duplicate front-page start marker.');
  assert(current.indexOf(FRONT_PAGE_END, end + FRONT_PAGE_END.length) === -1, 'Duplicate front-page end marker.');
  return current.slice(0, start + FRONT_PAGE_START.length) + '\n' + generated + '\n  ' + current.slice(end);
}

function jsonLd(value) {
  return JSON.stringify(value).replace(/</g, '\\u003c');
}

function assetUrl(publicPath) {
  const file = path.join(ROOT, publicPath.slice(1));
  if (!fs.existsSync(file)) return publicPath;
  const content = fs.readFileSync(file, 'utf8').replace(/\r\n?/g, '\n');
  const hash = crypto.createHash('md5').update(content).digest('hex').slice(0, 8);
  return publicPath + '?v=' + hash;
}

function rawAssetHash(publicPath) {
  return crypto.createHash('md5').update(fs.readFileSync(path.join(ROOT, publicPath.slice(1)))).digest('hex').slice(0, 8);
}

