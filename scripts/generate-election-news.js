function assert(condition, message) {
  if (!condition) throw new Error(message);
}

function isDate(value) {
  if (typeof value !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(value)) return false;
  const date = new Date(value + 'T00:00:00Z');
  return !Number.isNaN(date.getTime()) && date.toISOString().slice(0, 10) === value;
}

function host(value) {
  try {
    return new URL(value).hostname.toLowerCase().replace(/^www\./, '');
  } catch {
    return '';
  }
}

function validText(value, min, max) {
  return typeof value === 'string'
    && value.trim() === value
    && value.length >= min
    && value.length <= max
    && !/[<>]/.test(value)
    && Array.from(value).every((char) => {
      const point = char.codePointAt(0);
      return point === 9 || point === 10 || point === 13 ||
        (point >= 0x20 && point <= 0xd7ff) ||
        (point >= 0xe000 && point <= 0xfffd) ||
        (point >= 0x10000 && point <= 0x10ffff);
    })
    && !value.includes('—');
}

function validateModel(data, tracker, officialLedger) {
  assert(data && data.version === 1, 'Election news version must be 1.');
  assert(data.toolId === 'africa-election-tracker', 'Election news toolId is invalid.');
  assert(data.localeRoutes && typeof data.localeRoutes === 'object', 'localeRoutes is required.');
  assert(data.localeRoutes.en === '/tools/africa-election-tracker/news/', 'English newsroom route must remain canonical.');
  assert(Array.isArray(data.articles), 'Election news articles must be an array.');

  const routes = Object.entries(data.localeRoutes);
  const seenRoutes = new Set();
  for (const [locale, route] of routes) {
    assert(OWNED_ROUTES[locale], 'Unsupported election news locale: ' + locale);
    assert(route === OWNED_ROUTES[locale], 'Election news route must remain within its owned directory for ' + locale + '.');
    assert(!seenRoutes.has(route), 'Duplicate election news route: ' + route);
    seenRoutes.add(route);
  }

  const elections = new Map((tracker.elections || []).map((item) => [item.id, item]));
  const officialSources = new Map((officialLedger.sources || []).map((item) => [item.id, item]));
  const seenSlugs = new Set();

  for (const article of data.articles) {
    const context = article && article.slug || '(missing slug)';
    assert(article && /^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(article.slug || ''), 'Invalid article slug: ' + context);
    assert(!seenSlugs.has(article.slug), 'Duplicate election news slug: ' + article.slug);
    seenSlugs.add(article.slug);
    assert(elections.has(article.electionId), context + ': unknown electionId.');
    assert(Array.isArray(article.officialSources) && article.officialSources.length > 0, context + ': dated official source required.');
    assert(article.localizations && typeof article.localizations === 'object', context + ': localizations required.');
    assert(article.localizations.en, context + ': English source-reviewed content required.');

    const seenSourceUrls = new Set();
    for (const source of article.officialSources) {
      const ledgerSource = officialSources.get(source.officialSourceId);
      assert(ledgerSource, context + ': source is not in the official-source ledger.');
      assert(ledgerSource.country === elections.get(article.electionId).countryCode, context + ': official source country does not match the election.');
      assert(validText(source.label, 8, 150), context + ': source label is invalid.');
      assert(typeof source.url === 'string' && source.url.startsWith('https://'), context + ': source URL must use HTTPS.');
      assert(!/[\u0000-\u001f\u007f<>]/.test(source.url), context + ': source URL has invalid characters.');
      const sourceHost = host(source.url);
      const ledgerHost = host(ledgerSource.url);
      assert(sourceHost && ledgerHost && (sourceHost === ledgerHost || sourceHost.endsWith('.' + ledgerHost)), context + ': source URL does not match its official ledger host.');
      assert(!seenSourceUrls.has(source.url), context + ': duplicate official source URL.');
      seenSourceUrls.add(source.url);
      assert(isDate(source.publishedOn), context + ': official source needs a valid publication date.');
      assert(isDate(source.checkedOn) && source.checkedOn >= source.publishedOn, context + ': official source needs a valid checkedOn date.');
    }
    const latestSourcePublication = article.officialSources.map((source) => source.publishedOn).sort().at(-1);
    const latestSourceCheck = article.officialSources.map((source) => source.checkedOn).sort().at(-1);

    for (const [locale, content] of Object.entries(article.localizations)) {
      assert(LOCALE_NAMES[locale], context + ': unsupported localization ' + locale);
      assert(locale === 'en', context + ': localized articles require reviewed interface and feed translations before publication.');
      assert(data.localeRoutes[locale], context + ': localized article requires an explicit locale route for ' + locale);
      assert(content.reviewStatus === 'source-reviewed', context + ': ' + locale + ' content must be source-reviewed.');
      assert(isDate(content.reviewedOn), context + ': ' + locale + ' needs reviewedOn.');
      assert(isDate(content.publishedOn), context + ': ' + locale + ' needs publishedOn.');
      assert(isDate(content.updatedOn) && content.updatedOn >= content.publishedOn && content.updatedOn >= content.reviewedOn, context + ': ' + locale + ' has invalid updatedOn.');
      assert(content.publishedOn >= latestSourcePublication, context + ': article predates its source.');
      assert(content.reviewedOn >= latestSourceCheck, context + ': review predates source check.');
      assert(validText(content.headline, 30, 145), context + ': ' + locale + ' headline is invalid.');
      assert(validText(content.summary, 80, 300), context + ': ' + locale + ' summary is invalid.');
      assert(Array.isArray(content.paragraphs) && content.paragraphs.length >= 2, context + ': ' + locale + ' needs at least two paragraphs.');
      assert(content.paragraphs.every((paragraph) => validText(paragraph, 70, 1500)), context + ': ' + locale + ' has a missing, HTML, or undersized paragraph.');
      assert(content.paragraphs.join(' ').length >= 330, context + ': ' + locale + ' brief is too thin.');
    }
  }

  return { elections };
}

function escapeHtml(value) {
  return String(value).replace(/&/g, '&amp;').replace(/</g, '&lt;')
    .replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;');
}

function escapeXml(value) {
  return String(value).replace(/&/g, '&amp;').replace(/</g, '&lt;')
    .replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&apos;');
}

function formatDate(value, locale) {
  const date = new Date(value + 'T00:00:00Z');
  return new Intl.DateTimeFormat(locale === 'en' ? 'en-GB' : locale, {
    day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC'
  }).format(date);
}

function routeToFile(route) {
  return route.slice(1) + 'index.html';
}

function articleRoute(baseRoute, slug) {
  return baseRoute + slug + '/';
}

function calendarLabel(record) {
  if (record.datePrecision === 'year') return String(record.electionDate).slice(0, 4);
  if (record.datePrecision === 'month' || record.dateStatus === 'projected' || record.dateStatus === 'tentative') {
    return new Intl.DateTimeFormat('en-GB', { month: 'long', year: 'numeric', timeZone: 'UTC' })
      .format(new Date(record.electionDate + 'T00:00:00Z'));
  }
  return formatDate(record.electionDate, 'en');
}

